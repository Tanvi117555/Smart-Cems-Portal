async function seedInitialData() {
  console.log('🌱 Checking & Seeding Built-In Campus Events...');

  let eventsSeeded = 0;
  for (const ev of SAMPLE_EVENTS) {
    try {
      const docRef = db.collection('events').doc(ev.id);
      const existingDoc = await docRef.get();

      if (!existingDoc.exists) {
        await docRef.set({
          ...ev,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString()
        });
        eventsSeeded++;
      } else {
        // Ensure critical fields like banner, payment qr, and schedule are populated
        const existingData = existingDoc.data();
        await docRef.set({
          ...ev,
          ...existingData,
          rules: ev.rules,
          schedule: ev.schedule,
          image: existingData.image || ev.image,
          bannerImage: existingData.bannerImage || ev.bannerImage,
          paymentQrUrl: ev.payment_qr_url || existingData.paymentQrUrl,
          qr_code_image: ev.payment_qr_url || existingData.qr_code_image,
          organizerId: existingData.organizerId || ev.organizerId,
          organizer_id: existingData.organizer_id || ev.organizer_id,
          updatedAt: new Date().toISOString()
        }, { merge: true });
      }

      // Seed feedback form for the event if missing
      const formsSnapshot = await docRef.collection('feedbackForms').limit(1).get();
      if (formsSnapshot.empty) {
        const formRef = await docRef.collection('feedbackForms').add({
          eventId: ev.id,
          title: `${ev.title} — Feedback & Experience Survey`,
          description: 'Please help us enhance campus events by rating your participation and learning experience.',
          status: 'active',
          version: 1,
          createdAt: new Date().toISOString()
        });

        // Add questions subcollection
        for (const q of DEFAULT_FEEDBACK_QUESTIONS) {
          await formRef.collection('questions').add({
            ...q,
            createdAt: new Date().toISOString()
          });
        }
      }
    } catch (err) {
      console.warn(`Warning during seeding event ${ev.title}:`, err.message);
    }
  }

  console.log(`✅ Event database verified: ${SAMPLE_EVENTS.length} realistic events active.`);
  return true;
}

